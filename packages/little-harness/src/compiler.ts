import { sourceFiles, skillPaths, readSkillTree, fileExists, regularFile } from "./workspace/folder-layout.js";
/** Node-only build step. Emits static ESM; bundle the result with your worker entry point. */
import { readFile } from "node:fs/promises";
import { basename, join, parse, relative, resolve, sep } from "node:path";
import { parseFrontmatter } from "./skills/frontmatter.js";
import { loadWorkspace } from "./workspace/load-harness.js";
import { rejectReservedDiscoveredToolNames } from "./workspace/tool-name-policy.js";

export type CompileHarnessOptions = {
  /** Directory where the generated module will be written (imports are relative to it). */
  moduleDir: string;
  /** Fail rather than silently truncating bundled skill assets. Default: 2 MB per skill. */
  maxSkillBytes?: number;
};
/** Compile one agent.ts folder. Does not execute agent, tool, workflow or skill modules. */
export async function compileHarnessFolder(folder: string, options: CompileHarnessOptions): Promise<string> {
  const compiled = await compileFolder(resolve(folder), options, 0);
  return preamble(true, compiled.hasWorkflows) + compiled.imports.join("\n") + "\n" + compiled.declarations.join("\n") + "\nexport default " + compiled.factory + ";\n";
}

/** Compile the same immediate agent.ts folders and marker file that loadWorkspace discovers. */
export async function compileHarnessWorkspace(root: string, options: CompileHarnessOptions): Promise<string> {
  const { agents } = await loadWorkspace(root);
  const imports: string[] = [];
  const entries: string[] = [];
  const declarations: string[] = [];
  let hasWorkflows = false;
  for (const [index, agent] of agents.entries()) {
    const compiled = await compileFolder(agent.dir, options, index);
    imports.push(...compiled.imports);
    declarations.push(...compiled.declarations);
    hasWorkflows ||= compiled.hasWorkflows;
    entries.push(`[${JSON.stringify(agent.name)}, ${compiled.factory}]`);
  }
  return preamble(agents.length > 0, hasWorkflows) + imports.join("\n") + "\n" + declarations.join("\n") + `
const registry = new Map<string, (options: CompiledHarnessOptions) => Promise<Harness>>([${entries.join(",\n")}]);
export const agents: readonly string[] = Object.freeze(${JSON.stringify(agents.map(agent => agent.name))});
export async function loadHarness(name: string, options: CompiledHarnessOptions): Promise<Harness> {
  const factory = registry.get(name);
  if (factory === undefined) throw new Error("Unknown compiled agent: " + name);
  return factory(options);
}
`;
}

function preamble(hasAgents: boolean, hasWorkflows: boolean): string {
  const imports = hasAgents ? ["assembleHarness", "instantiateHarness", "assertBundledSkills"] : [];
  if (hasWorkflows) imports.push("validateDiscoveredWorkflow");
  return `// Generated by @little-stack/harness/compiler. Rebuild after changing the agent folders.
import { ${[...imports, "type CompiledHarnessOptions"].join(", ")} } from "@little-stack/harness/compiled";
import type { Harness } from "@little-stack/harness";
`;
}

async function compileFolder(dir: string, options: CompileHarnessOptions, index: number) {
  const limit = options.maxSkillBytes ?? 2_000_000;
  if (!Number.isSafeInteger(limit) || limit < 1) throw new Error("maxSkillBytes must be a positive integer.");
  await regularFile(join(dir, "agent.ts"));
  const imports: string[] = [];
  const declarations: string[] = [];
  let count = 0;
  function module(file: string): string {
    const name = `m_${index}_${count++}`;
    const path = relative(resolve(options.moduleDir), file).split(sep).join("/");
    imports.push(`import ${name} from ${JSON.stringify(path.startsWith("./") || path.startsWith("../") ? path : `./${path}`)};`);
    return name;
  }
  const agent = module(join(dir, "agent.ts"));
  const tools: string[] = [];
  for (const file of await sourceFiles(join(dir, "tools"), { strict: true })) {
    const name = parse(file).name;
    rejectReservedDiscoveredToolNames([name]);
    // Computed keys preserve JS object semantics without __proto__ setters.
    tools.push(`[${JSON.stringify(name)}]: await ${module(file)}`);
  }
  const workflows = (await sourceFiles(join(dir, "workflows"), { strict: true })).map(file =>
    `validateDiscoveredWorkflow(await ${module(file)}, ${JSON.stringify(`workflows/${basename(file)}`)})`);
  const skills: string[] = [];
  for (const [skillIndex, found] of (await skillPaths(dir, { strict: true })).entries()) {
    if (found.module !== undefined) { skills.push(`await ${module(found.module)}`); continue; }
    const markdown = await readFile(join(found.dir, "SKILL.md"), "utf8");
    const { name, description } = parseFrontmatter(markdown);
    if (!name || !description) throw new Error(`Skill metadata requires name and description: ${found.dir}`);
    const assets = await readSkillTree(found.dir, { strict: true, maxBytes: limit });
    const files = Object.entries(assets).map(([key, data]) =>
      `[${JSON.stringify(key)}]: Uint8Array.from(atob(${JSON.stringify(Buffer.from(data).toString("base64"))}), c => c.charCodeAt(0))`);
    const id = `skill_${index}_${skillIndex}`;
    // Decode lazily once, then copy bytes so a factory cannot mutate another chat's skill input.
    declarations.push(`let ${id}_cache: Record<string, Uint8Array> | undefined;
function ${id}() {
  const files = ${id}_cache ??= { ${files.join(", ")} };
  return { name: ${JSON.stringify(name)}, description: ${JSON.stringify(description)}, files: Object.fromEntries(Object.entries(files).map(([name, bytes]) => [name, bytes.slice()])) };
}`);
    skills.push(`${id}()`);
  }
  const instructionFile = join(dir, "instructions.md");
  const instructions = await fileExists(instructionFile, { strict: true }) ? (await readFile(instructionFile, "utf8")).trim() : "";
  return { imports, declarations, hasWorkflows: workflows.length > 0, factory: `async (options: CompiledHarnessOptions): Promise<Harness> => {
  if (options?.host === undefined) throw new Error("Compiled agents require a per-chat host.");
  const base = await instantiateHarness(await ${agent}, options.host);
  const harness = assembleHarness(base, { tools: { ${tools.join(", ")} }, skills: [${skills.join(", ")}], workflows: [${workflows.join(", ")}]${instructions ? `, instructions: ${JSON.stringify(instructions)}` : ""} }, options);
  assertBundledSkills(harness.config.skills);
  return harness;
}` };
}
